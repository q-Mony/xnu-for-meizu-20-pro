#!/usr/bin/env python3
"""Build the public IOStorageFamily sources into the kernel.

NativeUfsBlock subclasses IOBlockStorageDevice, and the prelinked kext keeps no symbols, so
the class cannot be bound to absolute addresses offline. Compiling the pinned public sources
instead gives the kernel real definitions; the prelinked copy is dropped from [kernel.prelink]
roots so only one class with that name exists.

IOBlockStorageDriver's DriverKit bridge needs a header generated by DriverKit tooling, which
this tree does not carry. That bridge is only a perf-control fast path; the patched copy keeps
the plain IOPerfControlClient path.
"""
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'refer/IOStorageFamily'
OUT = ROOT / 'build/meizu-storage-family'
SRC = OUT / 'src'
OUT.mkdir(parents=True, exist_ok=True)
SRC.mkdir(parents=True, exist_ok=True)
SKIP = {'IOUserBlockStorageDevice_kext.cpp'}


def run(command, **kwargs):
    result = subprocess.run([str(v) for v in command], timeout=600, capture_output=True, text=True, **kwargs)
    if result.returncode:
        raise SystemExit(result.stdout[-3000:] + result.stderr[-3000:])
    return result.stdout


if not (SOURCE / '.git').is_dir():
    raise SystemExit(f'missing {SOURCE}; run "unixnu fetch IOStorageFamily" first')
revision = run(['git', '-C', SOURCE, 'rev-parse', 'HEAD']).strip()

sources = []
for path in sorted(SOURCE.glob('*.cpp')):
    if path.name in SKIP:
        continue
    data = path.read_text()
    if path.name == 'IOBlockStorageDriver.cpp':
        data = data.replace('#include "IOUserBlockStorageDevice_kext.h"\n', '')
        data = data.replace('_userBlockStorageDevice = OSDynamicCast(IOUserBlockStorageDevice, provider);',
                            '_userBlockStorageDevice = NULL; (void) provider;')
        data = data.replace('''    if (_userBlockStorageDevice) {
        _perfControlClient = _userBlockStorageDevice->getPerfControlClient();
        assert(_perfControlClient != NULL);
    }
    else {
''', '    {\n')
        if 'IOUserBlockStorageDevice' in data:
            raise SystemExit('IOBlockStorageDriver still references the DriverKit bridge')
    copy = SRC / path.name
    copy.write_text(data)
    sources.append(copy)

# NativeUfs pokes the boot-progress layer while it reads. This board has no such layer, and
# ld64 rejects the undefined weak reference, so the archive carries the empty definition.
stub = SRC / 'meizu-boot-progress-stub.cpp'
stub.write_text('extern "C" void boot_progress_poll(void) {}\n')
sources.append(stub)

recipe = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json').read_text().strip().rstrip(','))
objects = []
for source in sources:
    obj = OUT / (source.stem + '.o')
    command, index = [], 0
    arguments = recipe['arguments']
    while index < len(arguments):
        value = arguments[index]
        if value == recipe['file']:
            command.append(source)
        elif value == '-o':
            command += ['-o', obj]
            index += 1
        elif value == '-Xclang' and arguments[index + 1].startswith('-W'):
            index += 1
        elif not value.startswith('-W'):
            command.append(value)
        index += 1
    command += ['-I', SOURCE, '-I', ROOT / 'build/storage-abi/include',
                '-Wno-everything', '-Wno-error']
    result = subprocess.run([str(v) for v in command], cwd=recipe['directory'],
                            capture_output=True, text=True)
    if result.returncode:
        raise SystemExit(f'{source.name}:\n' + (result.stdout + result.stderr)[-3000:])
    objects.append(obj)

archive = OUT / 'libMeizuStorageFamily.a'
archive.unlink(missing_ok=True)
run(['xcrun', 'ar', 'rcs', archive, *[str(o) for o in objects]])
(OUT / 'build-report.json').write_text(json.dumps(dict(
    source_revision=revision, sources=[s.name for s in sources],
    archived=len(objects), archive_sha256=hashlib.sha256(archive.read_bytes()).hexdigest(),
    ios_storage_family_skipped=sorted(SKIP)), indent=2) + '\n')
print(f'PASS: {len(objects)} public IOStorageFamily objects archived')
